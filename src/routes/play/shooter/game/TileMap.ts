/** Returns all floor tile positions (center of tile in world coords). */
export function getFloorTiles(): { x: number; y: number }[] {
  const tiles: { x: number; y: number }[] = [];
  for (let r = 0; r < MAP_ROWS; r++) {
    for (let c = 0; c < MAP_COLS; c++) {
      if (MAP_DATA[r][c] === 0) {
        tiles.push({ x: c * TILE_SIZE + TILE_SIZE / 2, y: r * TILE_SIZE + TILE_SIZE / 2 });
      }
    }
  }
  return tiles;
}

/** Pick a random floor tile at least `minDist` px from any position in `avoid`. */
export function randomFloorTile(
  avoid: { x: number; y: number }[] = [],
  minDist = 200
): { x: number; y: number } {
  const floors = getFloorTiles();
  // Shuffle
  for (let i = floors.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [floors[i], floors[j]] = [floors[j], floors[i]];
  }
  // Find one far from avoid positions
  for (const tile of floors) {
    const tooClose = avoid.some((a) => Math.hypot(a.x - tile.x, a.y - tile.y) < minDist);
    if (!tooClose) return tile;
  }
  // Fallback: return any floor tile
  return floors[0];
}

/** Check if a tile at grid position is a wall. */
export function isWall(col: number, row: number): boolean {
  if (row < 0 || row >= MAP_ROWS || col < 0 || col >= MAP_COLS) return true;
  return MAP_DATA[row][col] === 1;
}

/** Check if a tile at grid position is a bush. */
export function isBush(col: number, row: number): boolean {
  if (row < 0 || row >= MAP_ROWS || col < 0 || col >= MAP_COLS) return false;
  return MAP_DATA[row][col] === 2;
}
